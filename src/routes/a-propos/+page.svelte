	<h1 class="font-heading text-3xl">À propos</h1>
	<p class="mt-4">
		Pères de l'Église est une anthologie patristique française, organisée par sujets. Le corpus est progressivement enrichi à partir de sources primaires (Patrologie Latine, Patrologie Grecque, Corpus Christianorum) et de traductions originales.
	</p>
	<p class="mt-3">
		Inspiré dans sa structure thématique par <em>The Fathers Know Best</em> de Jimmy Akin, le site vise à présenter, en français, la continuité de l'enseignement de l'Église à travers les Pères.
	</p>
